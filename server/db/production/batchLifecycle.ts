export async function generateBatchCode(productId: number, tenantId?: number) {
  const conn = await getRawConnection();

  // 1. 제품 정보 조회 (h_products_v2 단일 소스)
  let productCode = "00000";
  try {
    const productQuery = tenantId
      ? "SELECT product_code FROM h_products_v2 WHERE id=? AND tenant_id=? LIMIT 1"
      : "SELECT product_code FROM h_products_v2 WHERE id=? LIMIT 1";
    const productParams = tenantId ? [productId, tenantId] : [productId];
    const [rows] = await conn.execute<any[]>(productQuery, productParams);
    if ((rows as any[]).length > 0 && (rows as any[])[0].product_code) {
      productCode = (rows as any[])[0].product_code;
    }
  } catch { /* use default code */ }

  // 2. 오늘 날짜 문자열 생성 (YYYYMMDD) - KST 기준
  const today = new Date();
  const kstOffset = 9 * 60; // UTC+9
  const kstDate = new Date(today.getTime() + kstOffset * 60 * 1000);
  const dateStr = kstDate.toISOString().slice(0, 10).replace(/-/g, "");

  // 3. 해당 날짜의 기존 배치 수 조회 (tenantId 격리)
  const countParams: any[] = tenantId
    ? [tenantId, `${productCode}-${dateStr}-%`]
    : [`${productCode}-${dateStr}-%`];
  const countSql = tenantId
    ? "SELECT COUNT(*) as cnt FROM h_batches WHERE tenant_id=? AND batch_code LIKE ?"
    : "SELECT COUNT(*) as cnt FROM h_batches WHERE batch_code LIKE ?";
  const [countRows] = await conn.execute<any[]>(countSql, countParams);
  const seq = ((countRows as any[])[0]?.cnt || 0) + 1;

  // 4. 배치 번호 생성 (순번은 3자리로 패딩)
  return `${productCode}-${dateStr}-${String(seq).padStart(3, "0")}`;
}

export async function generateBatchReport(batchId: number, tenantId?: number) {
  const db = await getDb();
  if (!db) throw new Error("Database not available");

  const { hBatches, hProductsV2, hCcpInstances, hCcpRecords, hBatchInputs, hMaterials } = await import("../../../drizzle/schema");

  // 배치 정보 조회
  const batch = await db
    .select()
    .from(hBatches)
    .where(eq(hBatches.id, batchId))
    .limit(1)
    .then((rows) => rows[0]);

  if (!batch) {
    throw new Error("배치를 찾을 수 없습니다.");
  }

  // 제품 정보 조회 (h_products_v2 단일 소스)
  const product = await db
    .select()
    .from(hProductsV2)
    .where(eq(hProductsV2.id, batch.productId))
    .limit(1)
    .then((rows) => rows[0]);

  // CCP 인스턴스 조회
  const ccpInstances = await db
    .select()
    .from(hCcpInstances)
    .where(eq(hCcpInstances.batchId, batchId));

  // CCP 점검 기록 조회
  const ccpRecordsData: any[] = [];
  for (const instance of ccpInstances) {
    const records = await db
      .select()
      .from(hCcpRecords)
      .where(eq(hCcpRecords.instanceId, instance.id));
    ccpRecordsData.push(...records);
  }

  // 원재료 투입 내역 조회
  const materialInputs = await db
    .select({
      input: hBatchInputs,
      material: hMaterials
    })
    .from(hBatchInputs)
    .leftJoin(hMaterials, eq(hBatchInputs.materialId, hMaterials.id))
    .where(eq(hBatchInputs.batchId, batchId));

  return {
    batch,
    product,
    ccpInstances,
    ccpRecords: ccpRecordsData,
    materialInputs
  };
}

export async function getActiveBatches(tenantId?: number) {
  const db = await getDb();
  if (!db) throw new Error("Database connection failed");

  const { sql } = await import("drizzle-orm");

  // 최근 7일 이내의 배치 조회 (tenantId 격리)
  const tenantFilter = tenantId ? sql`AND b.tenant_id = ${tenantId}` : sql``;
  // ★ db.execute(sql) 는 [rows, fields] 튜플 반환 — [0] 으로 rows 추출 필수
  const batchesResult: any = await db.execute(sql`
    SELECT
      b.id as batchId,
      b.batch_code as batchNumber,
      b.planned_quantity as quantity,
      b.planned_date as startTime,
      DATE_ADD(b.planned_date, INTERVAL 8 HOUR) as expectedEndTime,
      p.product_name as productName,
      'in_progress' as status,
      (SELECT COUNT(*) FROM h_ccp_instances WHERE batch_id = b.id) as ccpCheckCount,
      (SELECT COUNT(*) FROM h_ccp_instances WHERE batch_id = b.id AND status = 'completed') as ccpCheckCompletedCount
    FROM h_batches b
    LEFT JOIN h_products_v2 p ON b.product_id = p.id AND p.tenant_id = b.tenant_id
    WHERE b.planned_date >= DATE_SUB(NOW(), INTERVAL 7 DAY) ${tenantFilter}
    ORDER BY b.planned_date DESC
    LIMIT 20
  `);
  const batchesRaw = ((batchesResult as any)?.[0] ?? []) as any[];

  return batchesRaw.map((row: any) => ({
    batchId: row.batchId,
    batchNumber: row.batchNumber,
    quantity: Number(row.quantity || 0),
    unit: "개",
    startTime: row.startTime,
    expectedEndTime: row.expectedEndTime,
    productName: row.productName || "알 수 없음",
    status: row.status,
    ccpCheckCount: Number(row.ccpCheckCount || 0),
    ccpCheckCompletedCount: Number(row.ccpCheckCompletedCount || 0)
  }));
}

export async function checkBatchCompletionReadiness(batchId: number, tenantId?: number) {
  const db = await getDb();
  if (!db) throw new Error("Database connection failed");

  // 배치 정보 조회 (tenantId 격리)
  const conditions: any[] = [eq(hBatches.id, batchId)];
  if (tenantId) conditions.push(eq(hBatches.tenantId, tenantId));

  const batches = await db
    .select()
    .from(hBatches)
    .where(and(...conditions))
    .limit(1);
  const batch = batches[0];

  if (!batch) {
    throw new Error("배치를 찾을 수 없습니다");
  }

  // 1. 원재료 투입 확인
  const materialInputs = await db
    .select()
    .from(hBatchInputs)
    .where(eq(hBatchInputs.batchId, batchId));

  const hasMaterialInputs = materialInputs.length > 0;

  // 2. CCP 점검 완료 확인
  const ccpInstances = await db
    .select()
    .from(hCcpInstances)
    .where(eq(hCcpInstances.batchId, batchId));

  let ccpCompletedCount = 0;
  let ccpTotalCount = ccpInstances.length;

  for (const instance of ccpInstances) {
    const records = await db
      .select()
      .from(hCcpRecords)
      .where(eq(hCcpRecords.instanceId, instance.id));

    if (records.length > 0) {
      ccpCompletedCount++;
    }
  }

  const ccpCompleted = ccpTotalCount === 0 || ccpCompletedCount === ccpTotalCount;

  // 체크리스트 결과
  const checks = {
    hasMaterialInputs: {
      passed: hasMaterialInputs,
      message: hasMaterialInputs
        ? `원재료 투입 완료 (${materialInputs.length}건)`
        : "원재료 투입 기록이 없습니다"
    },
    ccpCompleted: {
      passed: ccpCompleted,
      message: ccpCompleted
        ? `CCP 점검 완료 (${ccpCompletedCount}/${ccpTotalCount})`
        : `CCP 점검 미완료 (${ccpCompletedCount}/${ccpTotalCount})`
    }
  };

  const canComplete = hasMaterialInputs && ccpCompleted;
  const warnings: string[] = [];

  if (!hasMaterialInputs) {
    warnings.push("원재료 투입 기록이 없습니다.");
  }
  if (!ccpCompleted) {
    warnings.push(`CCP 점검이 완료되지 않았습니다 (${ccpCompletedCount}/${ccpTotalCount}).`);
  }

  return {
    canComplete,
    checks,
    warnings
  };
}

/**
 * 배치 완료 처리
 */
export async function completeBatch(params: {
  batchId: number;
  actualQuantity: number;
  defectQuantity?: number;
  revenue?: number;
  completionNotes?: string;
  idempotencyKey: string;
  tenantId: number; // P0 보안: 필수 (테넌트 격리)
}) {
  const { batchId, actualQuantity, defectQuantity, revenue, completionNotes, idempotencyKey, tenantId } = params;
  if (!tenantId) throw new Error("[P0 보안] completeBatch: tenantId는 필수입니다.");
  const db = await getDb();
  if (!db) throw new Error("Database connection failed");

  // 1. idempotency 키 검증 (중복 완료 방지, tenantId 격리)
  const batchConditions: any[] = [eq(hBatches.id, batchId), eq(hBatches.tenantId, tenantId)];
  if (tenantId) batchConditions.push(eq(hBatches.tenantId, tenantId));

  const existingBatches = await db
    .select()
    .from(hBatches)
    .where(and(...batchConditions))
    .limit(1);
  const existingBatch = existingBatches[0];

  if (!existingBatch) {
    throw new Error("배치를 찾을 수 없습니다");
  }

  if (existingBatch.completionIdempotencyKey === idempotencyKey) {
    throw new Error("이미 처리된 요청입니다 (중복 완료)");
  }

  if (existingBatch.status === "completed") {
    throw new Error("이미 완료된 배치입니다");
  }

  // 2. 배치 완료 처리 (원가 확정은 재고 정산 후 업데이트)
  await db
    .update(hBatches)
    .set({
      status: "completed",
      actualQuantity: actualQuantity.toString(),
      revenue: revenue?.toString(),
      notes: completionNotes,
      completionIdempotencyKey: idempotencyKey,
      completedAt: new Date(),
      endTime: new Date()
    })
    .where(eq(hBatches.id, batchId));

  // 3. 원재료 소비 및 재고 정산
  let totalMaterialCost = 0;
  let unissuedLines = -1; // 확인 전 = 판정 불가
  const issueErrors: string[] = [];
  try {
    const { hBatchInputs, hMaterials } = await import("../../../drizzle/schema");

    // 배치 투입 내역 (같은 회사)
    const batchInputs = await db
      .select({ input: hBatchInputs })
      .from(hBatchInputs)
      .where(and(eq(hBatchInputs.batchId, batchId), eq(hBatchInputs.tenantId, tenantId || existingBatch.tenantId)));

    // 정제수 판별 헬퍼
    const isWater = (name: string | null) => {
      if (!name) return false;
      const n = name.toLowerCase();
      return n.includes("정제수") || n.includes("purified water");
    };

    // 원재료 소비 처리 — 아직 출고되지 않은 줄은 자동출고 공통 진입점으로 (2026-10-17, 재고 쓰기 경로 PR-5)
    //   이전: 여기서 따로 h_inventory 를 GREATEST(0) 로 빼고, inventory_id JOIN 으로 찾은 LOT **하나** 에서 필요량 전체를
    //   0 클램프로 차감(모자라면 사라짐), 원장 lot_id=0·tenant 조건 없는 UPDATE, 트랜잭션 없음.
    //   또 이미 출고된 줄의 '실적 ≠ 출고 원장' 차이를 집계(h_inventory) 에만 GREATEST(0) 로 더해 LOT 정본에서 벗어났다.
    //   지금: 미출고 줄 → FEFO·관문·줄 단위 트랜잭션·배치 잠금. 실적 차이는 재고를 바꾸지 않고 경고만 (정정은 재고 조정으로).
    const effectiveTenantId = tenantId || existingBatch.tenantId;
    if (batchInputs.some(({ input }) => Number(input.inventoryDeducted) !== 1)) {
      try {
        const { autoIssueMaterialsDispatch } = await import("../../lib/production/autoMaterialIssueDispatcher");
        const issue = await autoIssueMaterialsDispatch(batchId, Number(existingBatch.createdBy) || 0, effectiveTenantId);
        if (issue.busy) issueErrors.push("다른 원료 출고가 진행 중입니다 — 끝난 뒤 '누락 출고 다시 실행' 으로 확인하세요.");
        issueErrors.push(...issue.errors);
      } catch (issueErr: any) {
        issueErrors.push(`원료 출고 실패: ${issueErr?.message || issueErr}`);
      }
    }
    // ★ Codex #552 검토 P1: 출고가 끝났는지 다시 센다 — 미출고 줄이 있으면 제품 LOT·생산원가를 확정하지 않고 응답에 알린다.
    //   (생산완료 사실은 남긴다. 재출고가 끝나면 매시 자가치유가 제품 LOT·완료 훅을 마저 실행한다.)
    try {
      const { countUnissuedBatchLines } = await import("../../lib/production/issuedBatchLines");
      unissuedLines = await countUnissuedBatchLines(batchId, effectiveTenantId);
    } catch (cntErr: any) {
      unissuedLines = -1; // 판정 불가 — 확정하지 않는다
      issueErrors.push(`출고 상태 확인 실패: ${cntErr?.message || cntErr}`);
    }

    // 원가 누적 (정제수 제외) — 출고 후 투입 행 기준
    const refreshed = await db
      .select({ input: hBatchInputs, materialName: hMaterials.materialName })
      .from(hBatchInputs)
      .leftJoin(hMaterials, eq(hBatchInputs.materialId, hMaterials.id))
      .where(and(eq(hBatchInputs.batchId, batchId), eq(hBatchInputs.tenantId, effectiveTenantId)));
    const pool = await getRawConnection();
    for (const { input, materialName } of refreshed) {
      if (Number(input.inventoryDeducted) !== 1) continue; // 출고 안 된 줄은 원가에 넣지 않음 (재출고 후 반영)
      if (!isWater(materialName)) totalMaterialCost += parseFloat(input.totalPrice?.toString() || "0");
      // 실적 vs 출고 원장 차이 — 재고는 바꾸지 않고 기록만
      try {
        const actualQty = parseFloat((input.actualQuantity || input.plannedQuantity || "0").toString());
        const [txRows]: any = await pool.execute(
          `SELECT COALESCE(SUM(quantity), 0) AS tx_total FROM h_inventory_transactions
            WHERE tenant_id = ? AND source_type = 'BATCH' AND source_id = ? AND source_line_id = ? AND transaction_type = 'usage'`,
          [effectiveTenantId, batchId, input.id],
        );
        const txTotal = parseFloat((txRows as any[])?.[0]?.tx_total || "0");
        if (txTotal > 0 && Math.abs(txTotal - actualQty) > 0.01) {
          console.warn(`[completeBatch] 배치#${batchId} ${materialName}: 출고 원장 ${txTotal} vs 실적 ${actualQty} — 재고 조정으로 정정 필요 (자동 보정 안 함)`);
        }
      } catch { /* 경고용 조회 */ }
    }

    // 완제품 재고는 제품 LOT 이 정본 — 제품 집계(h_inventory.product_id) 에 kg 를 더하지 않는다 (재고 결정 D2,
    //   SKU LOT 은 box/pack 단위라 섞인다). 이전: total/available += actualQuantity(kg).
    // 완제품 입고 기록은 SKU LOT 생성에서 처리
  } catch (error) {
    console.error(`[배치 완료] 재고 정산 실패:`, error);
  }

  // ★ 3-2. 제품 LOT 생성 — ensureBatchLots 하나로 (2026-10-17, 재고 쓰기 경로 PR-4)
  //   이전: 여기서 SKU LOT 을 직접 INSERT 하고, 이미 있으면 quantity·available 을 생산수량으로 **덮어써**
  //   그사이 판매·출고한 양이 되살아났다 (원장 없음, tenant 조건 없음, 트랜잭션 없음, 'inbound' created_by=1).
  //   지금: 관문 receiveNewLot·배치 잠금·이미 있으면 그대로 (완료를 다시 불러도 수량 복원 없음).
  const materialsSettled = unissuedLines === 0;
  if (!materialsSettled) {
    console.warn(`[completeBatch] 배치#${batchId}: 원료 미출고(${unissuedLines}줄) — 제품 LOT·생산원가 확정 보류`, issueErrors);
  }
  if (materialsSettled) try {
    const tenantId = existingBatch.tenantId;
    if (!tenantId) throw new Error('[P0 보안] tenantId is required for completeBatch');
    const { ensureBatchLots } = await import("./productOutboundManagement");
    const lotResult = await ensureBatchLots(batchId, tenantId);
    if (lotResult.skipped) {
      console.log(`[completeBatch] 배치 #${batchId}: 제품 LOT 생성 건너뜀 (${lotResult.reason})`);
    } else {
      console.log(`[completeBatch] 배치 #${batchId}: 제품 LOT ${lotResult.created.length}개 생성${lotResult.warning ? ` — ${lotResult.warning}` : ""}`);
    }
  } catch (skuLotErr) {
    console.error(`[completeBatch] 제품 LOT 생성 실패:`, skuLotErr);
  }

  // 3-1. 원가 확정 업데이트 (원료가 다 출고됐을 때만)
  if (materialsSettled && totalMaterialCost > 0) {
    await db
      .update(hBatches)
      .set({
        actualCost: totalMaterialCost.toFixed(2),
        costFinalizedAt: new Date()
      } as any)
      .where(eq(hBatches.id, batchId));
  }

  // 4. CCP 인스턴스 종결 (status: approved로 변경)
  await db
    .update(hCcpInstances)
    .set({ status: "approved" })
    .where(eq(hCcpInstances.batchId, batchId));

  // 5. 배치 완료 보고서 PDF 생성
  let pdfUrl: string | null = null;
  let pdfGenerated = false;
  try {
    const { generateBatchCompletionReport } = await import("../../reports/batchCompletionReport");
    pdfUrl = await generateBatchCompletionReport(batchId);
    pdfGenerated = true;
    console.log(`[Batch Completion] PDF report generated: ${pdfUrl}`);

    // PDF URL을 DB에 저장
    await db
      .update(hBatches)
      .set({ completionReportUrl: pdfUrl })
      .where(eq(hBatches.id, batchId));
  } catch (error) {
    console.error(`[Batch Completion] PDF generation failed:`, error);
    // PDF 생성 실패해도 배치 완료는 진행
  }
  // 6. [자동화] 배치 완료 시 문서 자동 생성 + 일일일지 + 승인 요청 트리거
  let autoGeneratedDocs: any[] = [];
  try {
    // 6-1. 문서 자동 생성 (★ 2026-04-15: tenantId 전달 - 테넌트 격리)
    autoGeneratedDocs = await autoGenerateDocumentsForBatch(
      batchId,
      existingBatch.siteId,
      existingBatch.productId,
      new Date(),
      1,
      existingBatch.tenantId,
    );
    console.log(`[Batch Completion] ${autoGeneratedDocs.length}건 문서 자동 생성`);

    // 6-2. 일일일지 자동 생성
    try {
      const rawConn2 = await getRawConnection();
      if (rawConn2) {
        const today = resolveBatchTransactionDate(existingBatch); // 생산일 기준 일일보고
        const now2 = toKSTTimestamp(new Date());
        await rawConn2.execute(
          "INSERT IGNORE INTO h_daily_reports (site_id, report_date, report_type, summary, status, created_at, updated_at) VALUES (?, ?, 'production', ?, 'completed', ?, ?)",
          [existingBatch.siteId, today, JSON.stringify({ batchId, actualQuantity, autoGenerated: true }), now2, now2]
        );
        console.log(`[Batch Completion] 일일일지 자동 생성 완료`);
      }
    } catch (dailyErr) {
      console.error(`[Batch Completion] 일일일지 자동 생성 실패:`, dailyErr);
    }

    // 6-3. 승인 요청 자동 생성
    if (autoGeneratedDocs.length > 0) {
      try {
        for (const doc of autoGeneratedDocs) {
          await db.insert(hApprovalRequests).values({
            batchId,
            siteId: existingBatch.siteId,
            documentInstanceId: doc.id,
            requestType: 'document_approval',
            title: `[자동] ${doc.documentTypeName} 승인 요청`,
            description: `배치 완료에 따른 ${doc.documentTypeName} 자동 승인 요청입니다.`,
            status: 'pending',
            requestedBy: 1,
            createdAt: new Date(),
          } as any);
        }
        console.log(`[Batch Completion] ${autoGeneratedDocs.length}건 승인 요청 자동 생성`);
      } catch (approvalErr) {
        console.error(`[Batch Completion] 승인 요청 자동 생성 실패:`, approvalErr);
      }
    }
  } catch (autoGenError) {
    console.error(`[Batch Completion] 자동 문서 생성 실패:`, autoGenError);
  }

  // ★ 7. 배치 완료 통합 훅 (PR #274) — 3개 완료 경로 공통 후처리
  //   - actual_quantity NULL 보강 (production_sku_output 합계 우선)
  //   - h_batch_inputs 0건 경고
  //   - h_daily_reports production_daily 캐시 무효화
  let hookResult: any = null;
  try {
    const { runBatchCompletionHooks } = await import(
      "../../lib/production/batchCompletionHooks"
    );
    hookResult = await runBatchCompletionHooks(batchId, existingBatch.tenantId, {
      source: "completeBatch",
    });
    if (hookResult.warnings.length > 0) {
      console.warn(
        `[Batch Completion] 통합 훅 경고 (배치#${batchId}):`,
        hookResult.warnings,
      );
    }
    if (hookResult.errors.length > 0) {
      console.error(
        `[Batch Completion] 통합 훅 오류 (배치#${batchId}):`,
        hookResult.errors,
      );
    }
  } catch (hookErr) {
    console.error(`[Batch Completion] 통합 훅 실행 실패:`, hookErr);
  }


  return {
    success: true,
    message: materialsSettled
      ? "배치가 성공적으로 완료되었습니다"
      : `생산완료는 기록했지만 원료 ${unissuedLines > 0 ? `${unissuedLines}줄이 ` : ""}출고되지 않아 제품 재고·생산원가는 확정하지 않았습니다. '누락 출고 다시 실행' 후 자동으로 반영됩니다.`,
    materialsSettled,
    unissuedLines: Math.max(unissuedLines, 0),
    issueErrors,
    data: {
      batchId,
      actualQuantity,
      defectQuantity,
      revenue,
      pdfGenerated,
      pdfUrl,
      autoGeneratedDocuments: autoGeneratedDocs.length,
      completionHooks: hookResult ? {
        backfilledActualQuantity: hookResult.backfilledActualQuantity,
        batchInputsCount: hookResult.batchInputsCount,
        invalidatedCacheRows: hookResult.invalidatedCacheRows,
        warnings: hookResult.warnings,
      } : null,
    }
  };
}

